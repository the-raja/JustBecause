/**
 * Dynamically extract unique categories from templates.
 * Ordered by natural popularity/shopping priority with "All" prepended.
 */
export function getCategories(templateList: Template[] = templates): string[] {
  const preferredOrder = [
    "All",
    "Love",
    "Birthday",
    "Proposal",
    "Flowers",
    "Story",
    "Anniversary",
    "Friendship",
    "Memories",
    "Interactive",
    "Apology",
    "Appreciation",
  ];
  const uniqueCategories = Array.from(
    new Set(templateList.map((t) => t.category.trim()))
  ).filter(Boolean);

  return [
    "All",
    ...preferredOrder.filter((cat) => cat !== "All" && uniqueCategories.includes(cat)),
    ...uniqueCategories.filter((cat) => !preferredOrder.includes(cat)).sort(),
  ];
}

/**
 * Returns exactly one representative template from each of three price tiers in this exact order:
 * 1. ₹49 (attractive entry-level surprise)
 * 2. ₹99 (interactive surprise)
 * 3. ₹149 (premium experience)
 * Total: exactly 3 cards maximum, deterministic selection, visually distinct experiences.
 */
export function getHomepageFeaturedTemplates(
  templateList: Template[] = templates
): Template[] {
  const preferred49Id = "birthday-candle";
  const preferred99Id = "3d-flower-garden";
  const preferred149Id = "universe";

  const item49 =
    templateList.find((t) => t.id === preferred49Id && t.price === 49) ||
    templateList.find((t) => t.price === 49);

  const item99 =
    templateList.find((t) => t.id === preferred99Id && t.price === 99) ||
    templateList.find((t) => t.price === 99);

  const item149 =
    templateList.find((t) => t.id === preferred149Id && t.price === 149) ||
    templateList.find((t) => t.price === 149);

  return [item49, item99, item149].filter((t): t is Template => Boolean(t));
}

/**
 * Extract only featured templates (delegates to getHomepageFeaturedTemplates for 3-tier variety).
 */
export function getFeaturedTemplates(templateList: Template[] = templates): Template[] {
  return getHomepageFeaturedTemplates(templateList);
}

/**
 * Filter templates by case-insensitive partial match across:
 * - title
 * - description
 * - category
 * - grade
 * - searchKeywords
 * In combination with the selected category.
 */
export function filterTemplates(
  templateList: Template[] = templates,
  query: string = "",
  category: string = "All"
): Template[] {
  const trimmedQuery = query.trim().toLowerCase();

  return templateList.filter((template) => {
    // 1. Category check
    if (category !== "All" && template.category.toLowerCase() !== category.toLowerCase()) {
      return false;
    }

    // 2. Query check (if empty, matches all within category)
    if (!trimmedQuery) {
      return true;
    }

    const matchesTitle = template.title.toLowerCase().includes(trimmedQuery);
    const matchesDescription = template.description.toLowerCase().includes(trimmedQuery);
    const matchesCategory = template.category.toLowerCase().includes(trimmedQuery);
    const matchesGrade = template.grade.toLowerCase().includes(trimmedQuery);
    const matchesKeywords = template.searchKeywords.some((keyword) =>
      keyword.toLowerCase().includes(trimmedQuery)
    );

    return matchesTitle || matchesDescription || matchesCategory || matchesGrade || matchesKeywords;
  });
}

/**
 * Sort templates by the given SortOption without mutating the input array.
 * - "relevance": Restores original curated order exactly.
 * - "price-asc": Sorts by numeric price ascending (stable: equal prices preserve curated order).
 * - "price-desc": Sorts by numeric price descending (stable: equal prices preserve curated order).
 */
export function sortTemplates(
  templateList: Template[],
  sortBy: SortOption = "relevance"
): Template[] {
  if (sortBy === "relevance") {
    return [...templateList];
  }

  return [...templateList].sort((a, b) => {
    if (sortBy === "price-asc") {
      return a.price - b.price;
    }
    if (sortBy === "price-desc") {
      return b.price - a.price;
    }
    return 0;
  });
}

